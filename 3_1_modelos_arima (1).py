# Function for unit root tests with detailed interpretation, including Random Walk
def unit_root_tests(series, name):
    print(f"\nUnit Root Tests for {name}:")

    # ADF Test
    adf_result = adfuller(series)
    print("ADF Test:")
    print(f'ADF Statistic: {adf_result[0]:.4f}')
    print(f'p-value: {adf_result[1]:.4f}')
    print(f'Critical Values: {adf_result[4]}')
    print("Interpretation:")
    if adf_result[1] < 0.05:
        print(f"  - p-value < 0.05: Reject null hypothesis - {name} is stationary")
        print(f"    Implication: {name} does not have a unit root and is suitable for modeling without differencing.")
        print(f"    Random Walk: {name} does NOT follow a Random Walk (since it is stationary).")
    else:
        print(f"  - p-value >= 0.05: Fail to reject null - {name} may be non-stationary")
        print(f"    Implication: {name} may have a unit root; consider differencing or further analysis.")
        print(f"    Random Walk: {name} may follow a Random Walk (since it has a unit root).")

    # KPSS Test
    kpss_result = kpss(series)
    print("\nKPSS Test:")
    print(f'KPSS Statistic: {kpss_result[0]:.4f}')
    print(f'p-value: {kpss_result[1]:.4f}')
    print(f'Critical Values: {kpss_result[3]}')
    print("Interpretation:")
    if kpss_result[1] < 0.05:
        print(f"  - p-value < 0.05: Reject null hypothesis - {name} is non-stationary")
        print(f"    Implication: {name} may require differencing to achieve stationarity for modeling.")
    else:
        print(f"  - p-value >= 0.05: Fail to reject null - {name} may be stationary")
        print(f"    Implication: {name} appears stationary and may not need differencing.")

    # Combined Interpretation
    print("\nCombined Interpretation:")
    if adf_result[1] < 0.05 and kpss_result[1] >= 0.05:
        print(f"  - Both tests agree: {name} is stationary. Suitable for modeling as-is.")
        print(f"    Random Walk Conclusion: {name} does NOT follow a Random Walk.")
    elif adf_result[1] >= 0.05 and kpss_result[1] < 0.05:
        print(f"  - Both tests agree: {name} is non-stationary. Differencing or transformation may be required.")
        print(f"    Random Walk Conclusion: {name} likely follows a Random Walk.")
    else:
        print(f"  - Tests disagree: Mixed evidence on stationarity for {name}. Consider further analysis (e.g., differencing, trend analysis).")
        print(f"    Random Walk Conclusion: Uncertain - further analysis needed to determine if {name} follows a Random Walk.")

